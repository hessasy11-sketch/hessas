/*
  # إضافة عمود user_id لربط حسابات المستثمرين بنظام Auth
  
  ## التغييرات
  
  1. إضافة عمود `user_id` لجدول `b2f_investor_accounts`
     - يربط حساب المستثمر مع حساب Auth
     - يسمح بتسجيل دخول آمن
     - nullable للسماح بالحسابات القديمة بدون Auth
  
  2. إضافة فهرس للأداء
     - فهرس على `user_id` لتحسين سرعة الاستعلام
  
  3. تحديث سياسات RLS
     - السماح للمستخدمين المصادقين بتحديث حساباتهم فقط
*/

-- ===============================================
-- 1. إضافة عمود user_id
-- ===============================================

ALTER TABLE b2f_investor_accounts
ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE;

-- ===============================================
-- 2. إضافة فهرس للأداء
-- ===============================================

CREATE INDEX IF NOT EXISTS idx_b2f_investor_accounts_user_id
  ON b2f_investor_accounts(user_id);

-- ===============================================
-- 3. تحديث التعليق على الجدول
-- ===============================================

COMMENT ON COLUMN b2f_investor_accounts.user_id IS 'ربط مع حساب المصادقة (auth.users) - اختياري للسماح بحسابات بدون تسجيل دخول';
