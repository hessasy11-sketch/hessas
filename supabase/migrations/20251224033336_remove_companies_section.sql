/*
  # حذف قسم مزادات الشركات

  1. التغييرات
    - حذف جميع الفئات المتعلقة بقسم الشركات
    - تحويل أي مزادات في قسم الشركات إلى القسم العام

  2. الأقسام المتبقية
    - public (المزادات العامة)
    - official (المزادات الرسمية)

  3. ملاحظات
    - سيتم حذف جميع البيانات المتعلقة بقسم الشركات نهائياً
    - المزادات سيتم تحويلها إلى القسم العام للحفاظ عليها
*/

-- حذف الفئات المتعلقة بقسم الشركات
DELETE FROM categories WHERE section = 'companies';

-- تحويل أي مزادات في قسم الشركات إلى القسم العام
UPDATE auctions 
SET section = 'public' 
WHERE section = 'companies';
